// Regenerates internal/hiscores/names_gen.go from the same osrs-json-hiscores release the Site
// pins. The sweep's snapshot keys MUST match the Site's byte for byte — a tile tracking
// `trackedStat: "zulrah"` scores off a key this table produces, so a drift here silently zeroes
// tracking rather than erroring.
//
// Run after bumping osrs-json-hiscores in Anvil.Site:
//   node scripts/gen-hiscores-names.mjs && gofmt -w internal/hiscores/names_gen.go
//
// A boss that is live on the hiscores but missing from the pinned release goes in
// extraBosses (internal/hiscores/names.go), mirroring EXTRA_HISCORE_BOSSES in the Site's
// src/lib/hiscores.ts. Prune both once a lib bump ships it.

import { createRequire } from 'node:module';
import { writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const sitePkg = resolve(here, '../../Anvil.Site/node_modules/osrs-json-hiscores/lib/utils/constants.js');

if (!existsSync(sitePkg)) {
  console.error(`Cannot find osrs-json-hiscores at ${sitePkg}\nRun \`npm install\` in Anvil.Site first.`);
  process.exit(1);
}

const require = createRequire(import.meta.url);
const c = require(sitePkg);

const version = require(resolve(here, '../../Anvil.Site/node_modules/osrs-json-hiscores/package.json')).version;

/** Go string literal, escaping the few characters that appear in OSRS names. */
const lit = (s) => `"${String(s).replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`;

/** `key: "Formatted Name"` pairs, in the source array's order so diffs stay readable. */
function pairs(keys, formatted) {
  return keys
    .map((k) => {
      const name = formatted[k];
      if (name === undefined) throw new Error(`no formatted name for ${k}`);
      return `\t${lit(k)}: ${lit(name)},`;
    })
    .join('\n');
}

const out = `// Code generated by scripts/gen-hiscores-names.mjs. DO NOT EDIT.
// Source: osrs-json-hiscores@${version} (as pinned by Anvil.Site).
//
// The official hiscores JSON endpoint returns activities and skills by DISPLAY NAME, and the ids
// are not stable across game updates — so every lookup here matches on a case-folded name, exactly
// as the Site's parseJsonStats does. These maps are the contract between the two: change one
// without the other and stat tiles stop scoring.

package hiscores

// SkillNames maps our canonical skill key to the hiscores display name.
var SkillNames = map[string]string{
${pairs(c.SKILLS, c.FORMATTED_SKILL_NAMES)}
}

// SkillOrder is the canonical skill key order (overall first), for stable iteration.
var SkillOrder = []string{
${c.SKILLS.map((s) => `\t${lit(s)},`).join('\n')}
}

// BossNames maps our canonical boss key to the hiscores activity display name.
var BossNames = map[string]string{
${pairs(c.BOSSES, c.FORMATTED_BOSS_NAMES)}
}

// BossOrder is the canonical boss key order, for stable iteration.
var BossOrder = []string{
${c.BOSSES.map((s) => `\t${lit(s)},`).join('\n')}
}

// ClueNames maps our canonical clue key to the hiscores activity display name.
var ClueNames = map[string]string{
${pairs(c.CLUES, c.FORMATTED_CLUE_NAMES)}
}

// ClueOrder is the canonical clue key order, for stable iteration.
var ClueOrder = []string{
${c.CLUES.map((s) => `\t${lit(s)},`).join('\n')}
}

// BountyHunterNames maps our canonical Bounty Hunter mode key to its display name. Note there are
// both current and "(Legacy)" ladders — the Site keeps all four, so we do too.
var BountyHunterNames = map[string]string{
${pairs(c.BH_MODES, c.FORMATTED_BH_NAMES)}
}

// BountyHunterOrder is the canonical Bounty Hunter mode order, for stable iteration.
var BountyHunterOrder = []string{
${c.BH_MODES.map((s) => `\t${lit(s)},`).join('\n')}
}

// Standalone activities the Site reads as top-level fields rather than map entries.
const (
	ActivityLeaguePoints     = ${lit(c.FORMATTED_LEAGUE_POINTS)}
	ActivityDeadmanPoints    = ${lit(c.FORMATTED_DEADMAN_POINTS)}
	ActivityLastManStanding  = ${lit(c.FORMATTED_LMS)}
	ActivityPvpArena         = ${lit(c.FORMATTED_PVP_ARENA)}
	ActivitySoulWarsZeal     = ${lit(c.FORMATTED_SOUL_WARS)}
	ActivityRiftsClosed      = ${lit(c.FORMATTED_RIFTS_CLOSED)}
	ActivityColosseumGlory   = ${lit(c.FORMATTED_COLOSSEUM_GLORY)}
	ActivityCollectionsLogged = ${lit(c.FORMATTED_COLLECTIONS_LOGGED)}
)

// StatsPath is the official JSON endpoint's path, relative to the gamemode base URL.
const StatsPath = ${lit(c.JSON_STATS_URL)}
`;

const dest = resolve(here, '../internal/hiscores/names_gen.go');
writeFileSync(dest, out);
console.log(`wrote ${dest}`);
console.log(`  osrs-json-hiscores@${version}: ${c.SKILLS.length} skills, ${c.BOSSES.length} bosses, ${c.CLUES.length} clues`);
